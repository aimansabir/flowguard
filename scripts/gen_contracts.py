"""Regenerate the contract files from the Rust types.

    python scripts/gen_contracts.py

1. crates/core types -> contracts/flowguard.schema.json   (cargo, gen_schema)
2. that schema       -> packages/contracts/.../models.py  (datamodel-codegen)

Run it after changing anything in crates/core/src/contracts.rs, and commit
both generated files. Tests fail when either is stale.
"""

import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = ROOT / "contracts" / "flowguard.schema.json"
MODELS = ROOT / "packages" / "contracts" / "src" / "flowguard_contracts" / "models.py"
CODEGEN = "datamodel-code-generator==0.86.0"  # pinned so the output is reproducible


def main() -> None:
    schema = subprocess.run(
        ["cargo", "run", "-q", "-p", "flowguard-core", "--bin", "gen_schema"],
        cwd=ROOT, check=True, capture_output=True, text=True,
    ).stdout
    SCHEMA.write_text(schema, encoding="utf-8", newline="\n")
    subprocess.run(
        [
            "uvx", "--from", CODEGEN, "datamodel-codegen",
            "--input", str(SCHEMA),
            "--input-file-type", "jsonschema",
            "--output", str(MODELS),
            "--output-model-type", "pydantic_v2.BaseModel",
            "--target-python-version", "3.12",
            "--use-standard-collections",
            "--use-union-operator",
            "--enum-field-as-literal", "all",
            "--use-schema-description",
            "--use-field-description",
            "--field-constraints",
            "--use-double-quotes",
            "--use-title-as-name",
            "--collapse-root-models",
            "--use-annotated",
            "--formatters", "black", "isort",
            "--disable-timestamp",
            "--custom-file-header",
            "# GENERATED by scripts/gen_contracts.py from contracts/flowguard.schema.json. Do not edit.",
        ],
        cwd=ROOT, check=True,
    )
    print(f"wrote {SCHEMA.relative_to(ROOT)} and {MODELS.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
